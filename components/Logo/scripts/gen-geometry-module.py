import json, re, math, numpy as np
from PIL import Image
from scipy import ndimage as ndi
raw=json.load(open('raw.json'))
s=open('/mnt/user-data/uploads/1792250331039_vetwo-v2-horse.svg').read()
paths=re.findall(r'<path\b([^>]*)/>',s)
sil_d=re.search(r'\bd="([^"]*)"',paths[0]).group(1)
sil=np.array(Image.open('sil.png').convert('L'))>128
edge=sil^ndi.binary_erosion(sil)
dte=ndi.distance_transform_edt(~edge)
def plen(p): return sum(math.dist(p[i],p[i+1]) for i in range(len(p)-1))
tr=[]
for p in raw['traces']:
    L=plen(p)
    if L<40: continue
    # sample along polyline
    pts=[];
    for i in range(len(p)-1):
        for t in np.linspace(0,1,8,endpoint=False):
            pts.append((p[i][0]+(p[i+1][0]-p[i][0])*t,p[i][1]+(p[i+1][1]-p[i][1])*t))
    near=np.mean([dte[min(1023,int(y/2)),min(1023,int(x/2))]<=7 for x,y in pts])
    tr.append((p,L,near>=0.7))
tr.sort(key=lambda t:-t[1])
n=len(tr);cut=int(n*0.3)
out=[]
for i,(p,L,per) in enumerate(tr):
    d='M'+' L'.join(f'{x} {y}' for x,y in p)
    out.append(dict(id=f't{i:02d}',d=d,length=round(L),tier='primary' if i<cut else 'secondary',perimeter=bool(per),rank=i,start=p[0],end=p[-1]))
pads=sorted(raw['pads'],key=lambda q:(q[0]//1,q[1]))
# spatially even thinning order: golden-ratio permutation
order=sorted(range(len(pads)),key=lambda i:(i*0.6180339887)%1)
rank={idx:r for r,idx in enumerate(order)}
padout=[dict(id=f'p{i:02d}',x=q[0],y=q[1],r=q[2],rank=rank[i]) for i,q in enumerate(pads)]
print(n,'traces',sum(o['perimeter'] for o in out),'perimeter',cut,'primary',len(padout),'pads')
ts=f'''/* eslint-disable */
// GENERATED by scripts/extract-geometry.py + gen step from vetwo-v2-horse.svg (viewBox 2048). Do not edit by hand.
export const VETWO_VIEWBOX = 2048 as const

export type TraceTier = 'primary' | 'secondary'
export interface TraceDef {{
  readonly id: string
  readonly d: string
  readonly length: number
  readonly tier: TraceTier
  /** true when the trace follows the logo's outer silhouette edge */
  readonly perimeter: boolean
  /** 0 = longest; used for deterministic density thinning */
  readonly rank: number
  readonly start: readonly [number, number]
  readonly end: readonly [number, number]
}}
export interface PadDef {{
  readonly id: string
  readonly x: number
  readonly y: number
  readonly r: number
  /** 0..n-1 spatially-even thinning order */
  readonly rank: number
}}

/** Official silhouette outline (path 0 of vetwo-v2-horse.svg). */
export const SILHOUETTE_PATH: string =
  {json.dumps(sil_d)}

const RAW_TRACES: TraceDef[] = {json.dumps(out)}
export const TRACES: readonly TraceDef[] = Object.freeze(RAW_TRACES.map((t) => Object.freeze(t)))

const RAW_PADS: PadDef[] = {json.dumps(padout)}
export const PADS: readonly PadDef[] = Object.freeze(RAW_PADS.map((p) => Object.freeze(p)))
'''
ts=ts.replace('"start": [','"start": [')
open('pkg/src/geometry/vetwoV2.ts','w').write(ts)
